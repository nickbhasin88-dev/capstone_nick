"""
W-5 Timing of the cuts (audit/timing): the same 2026-2030 total of US bilateral aid lost, reshaped. For each of the
15 MOU countries the signed schedule (yearly cut fractions on US direct channels) is compared with flat, front-loaded,
back-loaded, linear phase-out, and delayed-by-one-year shapes that keep the same sum of yearly cut fractions (so the
same modelled aid lost over 2026-2030, because the cut is applied to a constant 2021-23 baseline), plus a pure
one-year shift (the 2030 cut falls out of the window, so the total falls). America First MOUs preset, US bilateral MOU
schedule only, dashboard defaults, 400 draws, seed 7, paired ranges.

    .venv/bin/python audit/timing/run_timing.py [--draws 400]

Outputs: RESULTS_timing.md, timing.csv. Read-only with respect to the model.
"""
from __future__ import annotations

import argparse
import logging
import sys
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "audit" / "reallocation"))
logging.disable(logging.WARNING)
import health_model as hm  # noqa: E402
import scenarios as scn  # noqa: E402
import run_reallocation_2027 as rr  # noqa: E402

fmt, sfmt, md_table = rr.fmt, rr.sfmt, rr.md_table
SERV = rr.SERVICES


def shapes(c):
    """Variants of a 5-year cut schedule c with the same sum (clipped at 100%; the clipped total is reported)."""
    c = np.asarray(c, dtype=float)
    S = c.sum()
    w = {"Flat": np.ones(5), "Front-loaded": np.array(scn.path_shape("Front-loaded")), "Back-loaded": np.array(scn.path_shape("Back-loaded")),
         "Linear phase-out": np.array(scn.path_shape("Linear phase-out")), "Delayed one year, same total": np.r_[0.0, c[:4]]}
    out = {"Signed": c}
    for k, v in w.items():
        out[k] = np.clip(S * v / v.sum(), 0, 1)
    out["Delayed one year, shifted (total falls)"] = np.r_[0.0, c[:4]]
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--draws", type=int, default=400)
    a = ap.parse_args()
    alloc = pd.read_csv(ROOT / "audit" / "reallocation" / "allocations_2027.csv").set_index("iso3")
    isos, names = list(alloc.index), alloc["country"].to_dict()
    I, P = hm.load_inputs(), hm.load_params()
    ci = I["ci"]
    sc0 = scn.build_scenario(rr.PRESET, {}, ci)
    sc0.pair = {}
    res, arrs = {}, {}
    for i in isos:
        for k, cuts in shapes(sc0.us_direct_path_by_country[i]).items():
            sc = scn.build_scenario(rr.PRESET, {}, ci)
            sc.pair = {}
            sc.us_direct_path_by_country[i] = [float(x) for x in cuts]
            r0 = hm.run_country(i, sc, rr.FISCAL, I, P, n_draws=0, keep_draws=True, mortality_trend=rr.TREND)
            rd = hm.run_country(i, sc, rr.FISCAL, I, P, n_draws=a.draws, keep_draws=True, mortality_trend=rr.TREND)
            U, Ud = r0["draws"]["units"], rd["draws"]["units"]
            yt = r0["years"].set_index("year")
            d = {"iso3": i, "shape": k, "cuts": " / ".join(f"{x:.0%}" for x in cuts), "sum_cuts": float(np.sum(cuts)),
                 "aid_lost_5y": float(yt["aid_lost_usd"].sum()), "deaths_5y": float(r0["totals"]["deaths_5y"]),
                 "deaths_after": float(r0["committed"]["after_2030"]), "infections_5y": float(r0["buckets"].set_index("bucket").loc["HIV", "infections_5y"])}
            d["committed"] = d["deaths_5y"] + d["deaths_after"]
            for n, ls in SERV.items():
                d[f"{n}_5y"] = float(sum(U[l][0, :].sum() for l in ls))
                d[f"{n}_peak"] = float(max(sum(U[l][0, t] for l in ls) for t in range(5)))
            d["all6_5y"] = sum(d[f"{n}_5y"] for n in SERV)
            d["ART_by_year"] = [float(U["hiv_art"][0, t]) for t in range(5)]
            d["deaths_by_year"] = [float(x) for x in yt["deaths"]]
            res[(i, k)] = d
            arrs[(i, k)] = {"ART_5y": Ud["hiv_art"].sum(axis=1), "all6_5y": sum(Ud[l].sum(axis=1) for ls in SERV.values() for l in ls),
                            "deaths_5y": np.asarray(rd["draw_totals"]["deaths_5y"], dtype=float),
                            "committed": np.asarray(rd["draw_totals"]["deaths_5y"], dtype=float) + np.asarray(rd["draw_totals"]["after_2030"], dtype=float)}
    R = pd.DataFrame(res.values())
    R.to_csv(HERE / "timing.csv", index=False)
    SH = list(shapes([0.1] * 5))

    def tot(k, m):
        return sum(res[(i, k)][m] for i in isos)

    def arr(k, m):
        return sum(arrs[(i, k)][m] for i in isos)

    def rng(x):
        return float(np.percentile(x, 2.5)), float(np.percentile(x, 97.5))

    md = ["# W-5. Timing: the same 2026-2030 cut, reshaped (no model changes)", "",
          "Generated by `audit/timing/run_timing.py`. America First MOUs preset, US bilateral MOU schedule only (US multilateral "
          f"exits off), dashboard defaults, {a.draws} draws, seed 7, paired ranges, 15 countries. Each country's signed yearly cut "
          "fractions (1 - MOU amount / `mou_us_ref`) are reshaped keeping their sum, so the modelled aid lost over 2026-2030 is "
          "the same (the yearly cut is applied to a fixed 2021-23 baseline). Shapes use `scenarios.path_shape`. 'Delayed one "
          "year, same total' moves every year's cut one year later and scales the four remaining years up; 'shifted' moves "
          "them later without scaling (the 2030 cut falls outside the window). People on service are summed over 2026-2030 "
          "(ART: patient-years off treatment over the five years). Deaths 2026-30 and deaths set in motion for 2031-35 are "
          "secondary; the 'committed' column adds them, which matters here because a later cut moves deaths past 2030.", ""]
    md += ["## Step 1. Schedules", "", md_table(["Country"] + SH, [[names[i]] + [res[(i, k)]["cuts"] for k in SH] for i in isos]), "",
           "Clipping: " + ("; ".join(f"{names[i]} {k} ({res[(i, k)]['sum_cuts']:.2f} vs signed {res[(i, 'Signed')]['sum_cuts']:.2f})" for i in isos for k in SH
                                     if k not in ("Signed", "Delayed one year, shifted (total falls)") and abs(res[(i, k)]["sum_cuts"] - res[(i, "Signed")]["sum_cuts"]) > 1e-6) or "none")
           + " (a shape that would need a cut above 100% in some year keeps 100% there, so its total is smaller).", ""]
    rows = []
    for k in SH:
        rows.append([k, fmt(tot(k, "aid_lost_5y") / 1e6, 1), fmt(tot(k, "ART_5y")), fmt(tot(k, "ART_peak")), fmt(tot(k, "TB treatment_5y")), fmt(tot(k, "Bednets_5y")),
                     fmt(tot(k, "Vaccines_5y")), fmt(tot(k, "all6_5y")), f"{fmt(tot(k, 'deaths_5y'))} ({fmt(rng(arr(k, 'deaths_5y'))[0])}-{fmt(rng(arr(k, 'deaths_5y'))[1])})",
                     fmt(tot(k, "deaths_after")), f"{fmt(tot(k, 'committed'))} ({fmt(rng(arr(k, 'committed'))[0])}-{fmt(rng(arr(k, 'committed'))[1])})", fmt(tot(k, "infections_5y"))])
    md += ["## Step 2. Totals, 15 countries", "",
           md_table(["Shape", "Aid lost 2026-30 US$M", "ART patient-years lost 2026-30", "Peak people off ART in a year", "TB courses lost", "Bednets lost", "Children unvaccinated",
                     "People losing a service 2026-30", "Deaths 2026-30 (range)", "Deaths 2031-35", "Deaths set in motion (range)", "HIV infections 2026-30"], rows), ""]
    rows = []
    for k in SH[1:]:
        dA = arr(k, "ART_5y") - arr("Signed", "ART_5y")
        d6 = arr(k, "all6_5y") - arr("Signed", "all6_5y")
        dD = arr(k, "deaths_5y") - arr("Signed", "deaths_5y")
        dC = arr(k, "committed") - arr("Signed", "committed")
        rows.append([k, sfmt(tot(k, "aid_lost_5y") / 1e6 - tot("Signed", "aid_lost_5y") / 1e6, 1),
                     f"{sfmt(tot(k, 'ART_5y') - tot('Signed', 'ART_5y'))} ({sfmt(rng(dA)[0])} to {sfmt(rng(dA)[1])})",
                     f"{sfmt(tot(k, 'all6_5y') - tot('Signed', 'all6_5y'))} ({sfmt(rng(d6)[0])} to {sfmt(rng(d6)[1])})",
                     f"{sfmt(tot(k, 'deaths_5y') - tot('Signed', 'deaths_5y'))} ({sfmt(rng(dD)[0])} to {sfmt(rng(dD)[1])})",
                     sfmt(tot(k, "deaths_after") - tot("Signed", "deaths_after")),
                     f"{sfmt(tot(k, 'committed') - tot('Signed', 'committed'))} ({sfmt(rng(dC)[0])} to {sfmt(rng(dC)[1])})"])
    md += ["Change versus the signed schedule (paired ranges):", "",
           md_table(["Shape", "Δ aid lost 2026-30 US$M", "Δ ART patient-years 2026-30 (range)", "Δ people losing a service 2026-30 (range)", "Δ deaths 2026-30 (range)", "Δ deaths 2031-35", "Δ deaths set in motion (range)"], rows), ""]
    md += ["## Step 3. What one year of delay buys, by country", "",
           "Signed minus 'Delayed one year, same total' (the same money lost over 2026-2030, one year later): patient-years of ART kept "
           "within 2026-2030, people kept on a service, and deaths (2026-30 and set in motion). The shifted variant (2030's cut "
           "drops out of the window) is the upper bound of what a delay buys inside the window.", ""]
    rows = []
    for i in isos:
        s, d, sh = res[(i, "Signed")], res[(i, "Delayed one year, same total")], res[(i, "Delayed one year, shifted (total falls)")]
        dD = arrs[(i, "Signed")]["deaths_5y"] - arrs[(i, "Delayed one year, same total")]["deaths_5y"]
        dC = arrs[(i, "Signed")]["committed"] - arrs[(i, "Delayed one year, same total")]["committed"]
        rows.append([names[i], s["cuts"], d["cuts"], fmt(s["ART_5y"]), sfmt(s["ART_5y"] - d["ART_5y"]), f"{(s['ART_5y'] - d['ART_5y']) / max(s['ART_5y'], 1):+.0%}",
                     sfmt(s["all6_5y"] - d["all6_5y"]), f"{sfmt(s['deaths_5y'] - d['deaths_5y'])} ({sfmt(rng(dD)[0])} to {sfmt(rng(dD)[1])})",
                     f"{sfmt(s['committed'] - d['committed'])} ({sfmt(rng(dC)[0])} to {sfmt(rng(dC)[1])})",
                     sfmt(s["ART_5y"] - sh["ART_5y"]), sfmt(s["committed"] - sh["committed"]), sfmt((sh["aid_lost_5y"] - s["aid_lost_5y"]) / 1e6, 1)])
    md += [md_table(["Country", "Signed cuts 2026-30", "Delayed, same total", "ART patient-years lost (signed)", "ART patient-years kept by delay", "share", "People kept on a service",
                     "Deaths averted 2026-30 (range)", "Deaths set in motion averted (range)", "Shifted: ART py kept", "Shifted: deaths set in motion averted", "Shifted: Δ aid lost US$M"], rows), ""]
    # ART off treatment by year, totals
    rows = [[k] + [fmt(sum(res[(i, k)]["ART_by_year"][t] for i in isos)) for t in range(5)] + [fmt(sum(res[(i, k)]["deaths_by_year"][t] for i in isos)) for t in range(5)] for k in SH]
    md += ["People off ART and deaths by calendar year, totals:", "",
           md_table(["Shape"] + [f"Off ART {y}" for y in rr.YEARS] + [f"Deaths {y}" for y in rr.YEARS], rows), ""]
    md += ["## Step 4. Mechanism and caveats", "",
           "- A patient-year off ART in year 1 of a cut carries a 1.3% excess death hazard, rising to 6-7% by years 5-7 off "
           "treatment (`health_model.ART_HAZARD`), and the cohort also transmits HIV while off treatment; TB cases spread 1-2 "
           "years after an untreated year; a missed birth cohort's vaccine-preventable deaths arrive over the following years. "
           "So the same patient-years lost later in the window produce fewer deaths inside 2026-2030 and more after it, and a "
           "delay shortens the time cohorts spend at the high end of the hazard curve before funding returns in 2031.",
           "- People on service: because the yearly cut is applied to a fixed baseline, the sum of patient-years lost over the "
           "window is the same for every equal-total shape unless a line is capped at the people covered; differences in the "
           "people columns are therefore cap and cohort effects only, and the honest headline for timing is the deaths "
           "column, not coverage.",
           "- Model boundary: funding is assumed back from 2031 and people off ART return at the `art_reengage` rate, and "
           "vaccine deaths beyond 2035 are not counted, so a back-loaded or delayed cut looks cheaper partly because part of "
           "its harm falls outside the model's window. Compare the 'set in motion' column, not the 2026-30 column alone.", ""]
    (HERE / "RESULTS_timing.md").write_text("\n".join(md))
    print("wrote RESULTS_timing.md, timing.csv")
    for k in SH:
        print(f"{k}: ART py {tot(k, 'ART_5y'):,.0f}; people {tot(k, 'all6_5y'):,.0f}; deaths {tot(k, 'deaths_5y'):,.0f}; committed {tot(k, 'committed'):,.0f}; aid {tot(k, 'aid_lost_5y') / 1e6:,.1f}")


if __name__ == "__main__":
    main()
