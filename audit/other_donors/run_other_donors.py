"""
W-10 Other-donor offset (audit/other_donors): how fast would every other donor's aid for HIV, TB, malaria and
immunization in each MOU country have to grow to replace the US bilateral cuts year by year, and how does that compare
with how fast it actually grew over 2015-2023? Donor-by-year totals come from the raw IHME DAH database in datasets/
(IHME_DAH_DATABASE_1990_2026, the file prepare_model.py builds model_data/dah_lines.csv from; it is not committed to
the repository), with IHME's elim_ch double-counting filter applied as in prepare_model.py and the four programme
areas the dashboard models (hiv, tb, mal, nch_cnv), constant 2023 US$. The US cut per year is the modelled aid lost
under the America First MOUs preset (US bilateral MOU schedule only, and with the preset's US multilateral exits).

    .venv/bin/python audit/other_donors/run_other_donors.py

Outputs: RESULTS_other_donors.md, other_donors.csv. Read-only with respect to the model.
"""
from __future__ import annotations

import logging
import sys
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "audit" / "reallocation"))
logging.disable(logging.WARNING)
import health_model as hm  # noqa: E402
import prepare_model as pm  # noqa: E402
import scenarios as scn  # noqa: E402
import run_reallocation_2027 as rr  # noqa: E402

fmt, sfmt, md_table = rr.fmt, rr.sfmt, rr.md_table
RAW = ROOT / "datasets" / "IHME_DAH_DATABASE_1990_2026_Y2026M09D18.CSV"
COLS = ["hiv_dah_23", "tb_dah_23", "mal_dah_23", "nch_cnv_dah_23"]


def cagr(a, b, years):
    return (b / a) ** (1 / years) - 1 if a > 0 and b > 0 else np.nan


def main():
    alloc = pd.read_csv(ROOT / "audit" / "reallocation" / "allocations_2027.csv").set_index("iso3")
    isos, names = list(alloc.index), alloc["country"].to_dict()
    need = ["year", "source", "channel", "recipient_isocode", "elim_ch", "prelim_est"] + COLS
    d = pd.read_csv(RAW, usecols=need, na_values=["-"], low_memory=False)
    d = d[(d.elim_ch == 0) & d.recipient_isocode.isin(isos)]
    d[COLS] = d[COLS].fillna(0.0)
    d["four"] = d[COLS].sum(axis=1) * 1e3                           # US$ (file is in thousands)
    d["src_grp"] = d.source.map(pm.source_group)
    d["us"] = d.src_grp.eq("United States")
    by = d.groupby(["recipient_isocode", "year", "us"]).four.sum().unstack("us").fillna(0.0).rename(columns={True: "us", False: "other"})
    I, P = hm.load_inputs(), hm.load_params()
    ci = I["ci"]
    F = hm.Fiscal(*scn.DEFAULT_FISCAL)
    sc_b = scn.build_scenario(rr.PRESET, {}, ci)
    sc_b.pair = {}
    sc_f = scn.build_scenario(rr.PRESET, {}, ci)
    rows = []
    for i in isos:
        o = by.loc[i]["other"]
        u = by.loc[i]["us"]
        G_b = hm.run_country(i, sc_b, F, I, P, n_draws=0, mortality_trend=rr.TREND)["years"].set_index("year")["aid_lost_usd"]
        G_f = hm.run_country(i, sc_f, F, I, P, n_draws=0, mortality_trend=rr.TREND)["years"].set_index("year")["aid_lost_usd"]
        o23 = float(o.loc[2023])
        o_base = float(o.loc[2021:2023].mean())
        # growth needed: other donors' aid grows at g from its 2021-23 average level so that the extra covers each year's cut
        def need_g(G):
            best = 0.0
            for y, cut in G.items():
                if cut <= 0:
                    continue
                g = ((o_base + cut) / o_base) ** (1 / (y - 2022)) - 1
                best = max(best, g)
            return best
        r = {"iso3": i, "country": names[i], "other_2015": float(o.loc[2015]), "other_2018": float(o.loc[2018]), "other_2023": o23, "other_2021_23": o_base,
             "us_2021_23": float(u.loc[2021:2023].mean()), "other_2024_prelim": float(o.get(2024, np.nan)), "other_2025_prelim": float(o.get(2025, np.nan)),
             "cagr_2015_23": cagr(float(o.loc[2015]), o23, 8), "cagr_2018_23": cagr(float(o.loc[2018]), o23, 5),
             "cagr_2015_23_3yr": cagr(float(o.loc[2013:2015].mean()), o_base, 8),
             "cut_2030_bilateral": float(G_b.loc[2030]), "cut_mean_bilateral": float(G_b.mean()), "cut_2030_with_exits": float(G_f.loc[2030]),
             "cut_2030_pct_other": float(G_b.loc[2030]) / o_base * 100, "need_g_bilateral": need_g(G_b), "need_g_with_exits": need_g(G_f),
             "prelim_2025_vs_2023": float(o.get(2025, np.nan)) / o23 - 1 if o23 else np.nan}
        rows.append(r)
    R = pd.DataFrame(rows).set_index("iso3")
    R.to_csv(HERE / "other_donors.csv")
    tot = R.sum(numeric_only=True)
    md = ["# W-10. Other-donor offset: the growth other donors would need (no model changes)", "",
          "Generated by `audit/other_donors/run_other_donors.py` from the raw IHME DAH database (datasets/, not committed; the "
          "source of `model_data/dah_lines.csv`; elim_ch = 0 rows; HIV, TB, malaria and vaccine programme areas; constant 2023 "
          "US$) and the America First MOUs preset (US bilateral MOU schedule only, and with the US multilateral exits). 'Other "
          "donors' = every source except the United States, through every channel. The growth needed is the constant yearly "
          "rate from the 2021-23 average at which the extra other-donor money covers the US cut in every year 2026-2030 (binding "
          "in 2030 for every country). IHME's 2024-25 preliminary estimates have no recipient-level rows, so the yearly table "
          "stops at 2023.", ""]
    md += ["## Step 1. By country", "",
           md_table(["Country", "Other donors 2015 US$M", "2021-23 avg", "US 2021-23 avg", "Other donors' growth 2015-23 (%/yr)", "2018-23", "US cut 2030 US$M (bilateral)",
                     "as % of other donors' aid", "Growth needed 2023-30 (%/yr), bilateral", "with multilateral exits"],
                    [[r.country, fmt(r.other_2015 / 1e6, 1), fmt(r.other_2021_23 / 1e6, 1), fmt(r.us_2021_23 / 1e6, 1), f"{r.cagr_2015_23:+.1%}", f"{r.cagr_2018_23:+.1%}",
                      fmt(r.cut_2030_bilateral / 1e6, 1), f"{r.cut_2030_pct_other:.0f}%", f"{r.need_g_bilateral:+.1%}", f"{r.need_g_with_exits:+.1%}"] for r in R.sort_values("need_g_bilateral", ascending=False).itertuples()]), "",
           f"Totals, 15 countries: other donors 2015 US${tot.other_2015 / 1e6:,.0f}M, 2021-23 average US${tot.other_2021_23 / 1e6:,.0f}M "
           f"({cagr(tot.other_2015, tot.other_2023, 8):+.1%} a year 2015-23); US 2021-23 average US${tot.us_2021_23 / 1e6:,.0f}M; US cut in 2030 "
           f"US${tot.cut_2030_bilateral / 1e6:,.0f}M bilateral ({tot.cut_2030_bilateral / tot.other_2021_23:.0%} of other donors' aid), US${tot.cut_2030_with_exits / 1e6:,.0f}M with "
           f"the multilateral exits; growth needed {((tot.other_2021_23 + tot.cut_2030_bilateral) / tot.other_2021_23) ** (1 / 8) - 1:+.1%} a year "
           f"(bilateral) or {((tot.other_2021_23 + tot.cut_2030_with_exits) / tot.other_2021_23) ** (1 / 8) - 1:+.1%} (with exits), against "
           f"{cagr(tot.other_2015, tot.other_2023, 8):+.1%} achieved 2015-23.", ""]
    md += ["## Step 2. Other donors' aid by year (US$M, four programme areas, constant 2023 US$)", "",
           md_table(["Country"] + [str(y) for y in range(2015, 2024)],
                    [[names[i]] + [fmt(by.loc[i].get("other", pd.Series()).get(y, np.nan) / 1e6, 1) for y in range(2015, 2024)] for i in isos]), "",
           "Caveats: IHME disbursement estimates (lumpy: net campaigns and Gavi tranches); 2024-25 values are preliminary global "
           "ratios, not country data; the modelled US cut is a cut fraction applied to the 2021-23 US direct-channel baseline, "
           "so the dollars here are the model's, not the MOU sheet's; Global Fund and Gavi money counts as 'other donors' even "
           "though the US funds part of it (the multilateral-exits variant removes the US share of those channels).", ""]
    (HERE / "RESULTS_other_donors.md").write_text("\n".join(md))
    print("wrote RESULTS_other_donors.md, other_donors.csv")
    print(R[["cagr_2015_23", "cut_2030_pct_other", "need_g_bilateral", "need_g_with_exits"]].round(3).to_string())


if __name__ == "__main__":
    main()
