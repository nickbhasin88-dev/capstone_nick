"""
W-1 Historical fiscal response (audit/fiscal_history): how government health spending (GHES) moved when aid fell, in
the model's own panel (model_data/panel.csv: IHME Financing Global Health, 98 countries, 2000-2023, constant 2023 US$
per person). The dashboard's benchmark is the pooled two-way fixed-effects regression in prepare_model.py
(regressions.json "fiscal_replacement"): d(GHES per capita) on falls in DAH per capita this year and last year, rises,
and GDP growth; theta = -(b_fall + b_fall_l1) = -0.19: GHES fell about 19 cents per dollar of aid lost (CI -0.45 to
+0.07). This script asks whether that number holds across income groups, aid dependence, regions and periods, or
is driven by a few countries, and shows the distribution of episode-level responses, not just the mean.

    .venv/bin/python audit/fiscal_history/run_fiscal_history.py

Outputs: RESULTS_fiscal_history.md, subsample_theta.csv, jackknife_theta.csv, episodes.csv. Read-only with respect
to the model; nothing in model_data/ is edited. The regression code is prepare_model.twoway_fe (imported, not
re-implemented).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "audit" / "reallocation"))
import prepare_model as pm  # noqa: E402  (twoway_fe, SSA)
from run_reallocation_2027 import fmt, md_table  # noqa: E402

MOU15 = ["BWA", "BDI", "CMR", "SWZ", "ETH", "KEN", "LSO", "LBR", "MDG", "MWI", "MOZ", "NGA", "RWA", "SLE", "UGA"]
XS = ["d_dah_pc_fall", "d_dah_pc_fall_l1", "d_dah_pc_rise", "d_gdp_pc"]
FALL_PCT = 0.15          # an episode: DAH per person falls by at least this share on the previous year
MIN_DAH_PC = 5.0         # and the previous year's DAH per person was at least US$5 (the IHME per-person series are rounded to whole dollars, so the fall is at least US$1)
PERIODS = {"2001-2009": (2001, 2009), "2010-2014 (PEPFAR flat funding, Global Fund Round 11 cancelled)": (2010, 2014),
           "2015-2019 (incl. post-Ebola 2016-17)": (2015, 2019), "2020-2021 (COVID)": (2020, 2021),
           "2022-2023 (post-COVID retrenchment)": (2022, 2023)}


def theta(fit: dict) -> tuple:
    """(theta, lo, hi): -(b_fall + b_fall_l1) with a 95% CI (independence approximation, as health_model.theta_historical)."""
    b = fit["coef"]["d_dah_pc_fall"] + fit["coef"]["d_dah_pc_fall_l1"]
    se = float(np.hypot(fit["se"]["d_dah_pc_fall"], fit["se"]["d_dah_pc_fall_l1"]))
    return -b, -b - 1.96 * se, -b + 1.96 * se


def fit_theta(df: pd.DataFrame) -> dict:
    f = pm.twoway_fe(df, "d_ghes_pc", XS)
    t, lo, hi = theta(f)
    return {"theta": t, "lo": lo, "hi": hi, "n_obs": f["n_obs"], "n_countries": f["n_countries"], "r2_within": f["r2_within"],
            "b_fall": f["coef"]["d_dah_pc_fall"], "b_fall_l1": f["coef"]["d_dah_pc_fall_l1"], "b_rise": f["coef"]["d_dah_pc_rise"]}


def main():
    pan = pd.read_csv(ROOT / "model_data" / "panel.csv")
    pan = pan[pan.year >= 2001].copy()
    reg = json.load(open(ROOT / "model_data" / "regressions.json"))["fiscal_replacement"]
    ci = pd.read_csv(ROOT / "model_data" / "country_inputs.csv").set_index("iso3")
    # groupings
    wb = pd.read_csv(ROOT / "ext_data" / "wb_country_entities.csv", usecols=["iso3166_1_alpha3", "income_groups", "name"]).dropna(subset=["iso3166_1_alpha3"])
    inc = wb.set_index("iso3166_1_alpha3")["income_groups"].to_dict()
    inc["KSV"] = inc.get("XKX", np.nan)
    names = wb.set_index("iso3166_1_alpha3")["name"].to_dict()
    names["KSV"] = "Kosovo"
    reg_who = pd.read_csv(ROOT / "ext_data" / "who_regions.csv").set_index("iso3")["who_region"].to_dict()
    dep = pan[pan.year.between(2015, 2023)].groupby("iso3").apply(lambda g: (g.dah_per_cap_mean / g.the_per_cap_mean).mean())
    dep_t = pd.qcut(dep, 3, labels=["low (bottom third)", "middle", "high (top third)"])
    pan["income"] = pan.iso3.map(inc)
    pan["region"] = pan.iso3.map(reg_who)
    pan["dep"] = pan.iso3.map(dep_t)
    pan["ssa"] = pan.iso3.isin(pm.SSA)
    pan["mou15"] = pan.iso3.isin(MOU15)

    md = ["# W-1. Historical fiscal response: did governments replace falling aid? (no model changes)", "",
          "Generated by `audit/fiscal_history/run_fiscal_history.py` from `model_data/panel.csv` (IHME Financing Global "
          "Health: government health spending (GHES), development assistance for health (DAH) and total health spending per "
          "person, constant 2023 US$, 98 dashboard-candidate countries, 2000-2023) using the model's own regression code "
          "(`prepare_model.twoway_fe`: country and year fixed effects, country-clustered standard errors). Benchmark: the "
          "dashboard's `fiscal_replacement` regression in `model_data/regressions.json`.", ""]

    # ------------------------------------------------------------------ 1. reproduce the benchmark
    full = fit_theta(pan)
    t_json = theta(reg)
    md += ["## Step 1. The benchmark reproduced", "",
           f"- regressions.json: b_fall {reg['coef']['d_dah_pc_fall']:+.3f}, b_fall_l1 {reg['coef']['d_dah_pc_fall_l1']:+.3f}, "
           f"theta = -(sum) = {t_json[0]:+.3f} (95% CI {t_json[1]:+.2f} to {t_json[2]:+.2f}), {reg['n_obs']} country-years, "
           f"{reg['n_countries']} countries, {reg['years'][0]}-{reg['years'][1]}, within-R2 {reg['r2_within']:.3f}.",
           f"- Re-run here: theta {full['theta']:+.3f} ({full['lo']:+.2f} to {full['hi']:+.2f}), n {full['n_obs']}, "
           f"{full['n_countries']} countries, within-R2 {full['r2_within']:.3f}. "
           + ("Matches." if abs(full["theta"] - t_json[0]) < 1e-3 else "DOES NOT MATCH."),
           "- Reading: when DAH per person falls by US$1, GHES per person changes by about -US$0.19 over that year and the "
           "next (it falls with the aid; nothing is replaced). The CI spans -0.45 to +0.07, so the pooled estimate cannot "
           "tell 'no response' from 'GHES falls 45 cents'. The coefficient on aid rises is "
           f"{full['b_rise']:+.3f}: GHES does not move when aid rises either.", ""]

    # ------------------------------------------------------------------ 2. subsamples
    subs = []

    def add(label, mask):
        d = pan[mask]
        if d.iso3.nunique() < 8:
            return
        r = fit_theta(d)
        subs.append({"group": label, **r})

    add("All countries", pan.iso3.notna())
    for g in ["low_income", "lower_middle_income", "upper_middle_income"]:
        add(f"Income: {g.replace('_', ' ')}", pan.income == g)
    for g in ["AFR", "AMR", "EMR", "EUR", "SEAR", "WPR"]:
        add(f"WHO region: {g}", pan.region == g)
    add("Sub-Saharan Africa", pan.ssa)
    add("Outside sub-Saharan Africa", ~pan.ssa)
    for g in ["low (bottom third)", "middle", "high (top third)"]:
        add(f"Aid dependence (DAH/THE 2015-23): {g}", pan.dep == g)
    add("The 15 MOU countries", pan.mou15)
    add("All except the 15 MOU countries", ~pan.mou15)
    for label, (y0, y1) in PERIODS.items():
        add(f"Years {label}", pan.year.between(y0, y1))
    S = pd.DataFrame(subs)
    S.to_csv(HERE / "subsample_theta.csv", index=False)
    md += ["## Step 2. Does the 19 cents hold across groups?", "",
           "The same regression on subsamples (country and year fixed effects within each subsample). Groups with fewer than 8 "
           "countries are not shown. Income groups: World Bank (ext_data/wb_country_entities.csv); regions: WHO; aid "
           "dependence: the country's mean DAH / total health spending 2015-2023, terciles. Sign convention throughout: theta "
           "is the GHES change per US$1 of aid lost, so theta < 0 means GHES fell with the aid (-0.19 = fell 19 cents), "
           "theta = 0 means GHES did not move, theta > 0 would mean replacement.", "",
           md_table(["Group", "theta (GHES change per US$1 of aid lost)", "95% CI", "Country-years", "Countries", "within-R2"],
                    [[r.group, f"{r.theta:+.2f}", f"{r.lo:+.2f} to {r.hi:+.2f}", r.n_obs, r.n_countries, f"{r.r2_within:.3f}"] for r in S.itertuples()]), ""]

    # ------------------------------------------------------------------ 3. jackknife
    jk = []
    for iso in sorted(pan.iso3.unique()):
        r = fit_theta(pan[pan.iso3 != iso])
        jk.append({"iso3": iso, "country": names.get(iso, iso), "theta_without": r["theta"], "shift": r["theta"] - full["theta"]})
    J = pd.DataFrame(jk).sort_values("shift")
    J.to_csv(HERE / "jackknife_theta.csv", index=False)
    top = pd.concat([J.head(5), J.tail(5)])
    md += ["## Step 3. Is it driven by a few countries? (leave-one-out)", "",
           f"theta re-estimated 98 times, each time without one country. Range {J.theta_without.min():+.3f} to "
           f"{J.theta_without.max():+.3f} (full sample {full['theta']:+.3f}); the ten countries that move it most:", "",
           md_table(["Country left out", "theta without it", "Shift"],
                    [[f"{r.country} ({r.iso3})", f"{r.theta_without:+.3f}", f"{r.shift:+.3f}"] for r in top.itertuples()]), "",
           "Jackknife standard error of theta: " + f"{np.sqrt((len(J) - 1) / len(J) * ((J.theta_without - J.theta_without.mean()) ** 2).sum()):.3f}"
           + " (the regression's own clustered SE gives " + f"{(full['hi'] - full['theta']) / 1.96:.3f}" + ").", ""]

    # ------------------------------------------------------------------ 4. episodes
    pan = pan.sort_values(["iso3", "year"])
    g = pan.groupby("iso3")
    pan["dah_prev"] = g.dah_per_cap_mean.shift(1)
    pan["ghes_prev"] = g.ghes_per_cap_mean.shift(1)
    pan["fall_share"] = -pan.d_dah_pc / pan.dah_prev
    pan["d_ghes_next"] = g.d_ghes_pc.shift(-1)
    # the country's typical yearly GHES change outside episodes (counterfactual trend)
    ep_mask = (pan.fall_share >= FALL_PCT) & (pan.dah_prev >= MIN_DAH_PC)
    typical = pan[~ep_mask].groupby("iso3").d_ghes_pc.median()
    pan["typical_d_ghes"] = pan.iso3.map(typical)
    # the year's common shock (the median across countries of that year's GHES change net of each country's usual
    # change; the regression's year fixed effect), so 2022-23's general post-COVID retrenchment is not read as a response
    pan["yr_shock"] = (pan.d_ghes_pc - pan.typical_d_ghes).groupby(pan.year).transform("median")
    pan["yr_shock_next"] = pan.groupby("iso3").yr_shock.shift(-1)
    E = pan[ep_mask].copy()
    E["d_ghes_2y"] = E.d_ghes_pc + E.d_ghes_next                       # this year and next, as in the regression
    E["excess_2y"] = E.d_ghes_2y - 2 * E.typical_d_ghes - E.yr_shock - E.yr_shock_next   # net of the country's usual change and the year's common shock
    E["cents_raw"] = E.d_ghes_2y / (-E.d_dah_pc)                       # per US$1 of aid lost: + = GHES rose (replacement), - = GHES fell with the aid
    E["cents_adj"] = E.excess_2y / (-E.d_dah_pc)
    E["dah_share_the_prev"] = (E.dah_prev / (E.the_per_cap_mean - E.d_dah_pc + 0 * E.the_per_cap_mean)).clip(upper=1)
    E = E.dropna(subset=["d_ghes_2y"])
    E["period"] = pd.cut(E.year, bins=[2000, 2009, 2014, 2019, 2021, 2023], labels=list(PERIODS))
    E["country"] = E.iso3.map(names)
    E[["iso3", "country", "year", "income", "region", "dep", "dah_prev", "d_dah_pc", "fall_share", "ghes_prev", "d_ghes_pc",
       "d_ghes_next", "typical_d_ghes", "d_ghes_2y", "excess_2y", "cents_raw", "cents_adj", "period"]].to_csv(HERE / "episodes.csv", index=False)

    def dist(d):
        w = -d.d_dah_pc.sum()
        wp = -(d.d_dah_pc * d.sp_pop_totl).sum()
        return {"episodes": len(d), "countries": d.iso3.nunique(),
                "ghes_fell_raw": (d.d_ghes_2y < 0).mean(), "ghes_below_trend": (d.excess_2y < 0).mean(),
                "ghes_above_trend": (d.excess_2y > 0).mean(),
                "median_adj": d.cents_adj.median(), "p25_adj": d.cents_adj.quantile(0.25), "p75_adj": d.cents_adj.quantile(0.75),
                "dollar_weighted_adj": d.excess_2y.sum() / w if w else np.nan,
                "pop_weighted_adj": (d.excess_2y * d.sp_pop_totl).sum() / wp if wp else np.nan}

    rows = []
    groups = [("All episodes", E.iso3.notna())]
    groups += [(f"Income: {g_.replace('_', ' ')}", E.income == g_) for g_ in ["low_income", "lower_middle_income", "upper_middle_income"]]
    groups += [("Sub-Saharan Africa", E.iso3.isin(pm.SSA)), ("Outside sub-Saharan Africa", ~E.iso3.isin(pm.SSA))]
    groups += [(f"Aid dependence: {g_}", E.dep == g_) for g_ in ["low (bottom third)", "middle", "high (top third)"]]
    groups += [("The 15 MOU countries", E.iso3.isin(MOU15))]
    groups += [(f"Years {p}", E.period == p) for p in PERIODS]
    for label, m in groups:
        d = E[m]
        if len(d) < 5:
            continue
        r = dist(d)
        rows.append([label, r["episodes"], r["countries"], f"{r['ghes_fell_raw']:.0%}", f"{r['ghes_below_trend']:.0%}", f"{r['ghes_above_trend']:.0%}",
                     f"{r['median_adj']:+.2f}", f"{r['p25_adj']:+.2f} to {r['p75_adj']:+.2f}", f"{r['dollar_weighted_adj']:+.2f}",
                     f"{r['pop_weighted_adj']:+.2f}"])
    md += ["## Step 4. Episode by episode: the distribution behind the mean", "",
           f"An episode is a year in which DAH per person fell by at least {FALL_PCT:.0%} on the previous year, from a level "
           f"of at least US${MIN_DAH_PC:.0f} per person. The response is the change in GHES per person over that year and "
           "the next (the regression's window) per US$1 of aid lost: negative = GHES fell with the aid, positive = GHES rose "
           "(replacement), the same convention as theta. 'Adjusted' subtracts the country's usual yearly GHES change (its "
           "median outside episodes) and the year's common shock across all countries (the median change in that year net "
           "of each country's usual change; the regression's year effect), so neither the usual upward trend nor a general "
           "retrenchment year is read as a response. Per-person values are rounded to whole dollars in the IHME file, so "
           "single episodes in low-spending countries are coarse (a US$1 step on GHES of US$5-10 per person). The "
           "dollar-weighted value is the total adjusted GHES change over the episodes divided by the total aid lost: per "
           "person (the regression's implicit weighting) and weighted by population (actual dollars, so large countries "
           "dominate).", "",
           md_table(["Group", "Episodes", "Countries", "GHES fell outright", "GHES below its trend", "GHES above its trend", "Median cents per US$1 (adj.)",
                     "Interquartile range (adj.)", "Dollar-weighted per person (adj.)", "Population-weighted (adj.)"], rows), ""]
    # largest episodes
    big = E.reindex(E.d_dah_pc.mul(E.sp_pop_totl).sort_values().index).head(15)
    md += ["The 15 largest episodes by total aid lost (per-person fall x population):", "",
           md_table(["Country", "Year", "DAH/person before", "Fall", "GHES/person before", "GHES change (2 years)", "Usual yearly change", "Cents per US$1 (adj.)"],
                    [[f"{r.country} ({r.iso3})", r.year, f"{r.dah_prev:.1f}", f"{-r.d_dah_pc:.1f} ({r.fall_share:.0%})", f"{r.ghes_prev:.1f}",
                      f"{r.d_ghes_2y:+.1f}", f"{r.typical_d_ghes:+.1f}", f"{r.cents_adj:+.2f}"] for r in big.itertuples()]), ""]
    # the 15 MOU countries' own episodes
    m15 = E[E.iso3.isin(MOU15)].sort_values(["iso3", "year"])
    md += ["Episodes in the 15 MOU countries:", "",
           md_table(["Country", "Year", "DAH/person before", "Fall", "GHES/person before", "GHES change (2 years)", "Usual yearly change", "Cents per US$1 (adj.)"],
                    [[f"{r.country} ({r.iso3})", r.year, f"{r.dah_prev:.1f}", f"{-r.d_dah_pc:.1f} ({r.fall_share:.0%})", f"{r.ghes_prev:.1f}",
                      f"{r.d_ghes_2y:+.1f}", f"{r.typical_d_ghes:+.1f}", f"{r.cents_adj:+.2f}"] for r in m15.itertuples()]), ""]

    # ------------------------------------------------------------------ 5. summary
    allr = dist(E)
    lic = S[S.group == "Income: low income"].iloc[0]
    dep_hi = S[S.group.str.startswith("Aid dependence") & S.group.str.contains("high")].iloc[0]
    m15 = S[S.group == "The 15 MOU countries"].iloc[0]
    n_sig = int(((S.lo > 0) | (S.hi < 0)).sum())
    md += ["## Step 5. Summary", "",
           f"- The pooled -0.19 is not a property of the countries facing the cuts. Low-income countries: theta {lic.theta:+.2f} "
           f"({lic.lo:+.2f} to {lic.hi:+.2f}, {lic.n_countries} countries); the most aid-dependent third: {dep_hi.theta:+.2f} "
           f"({dep_hi.lo:+.2f} to {dep_hi.hi:+.2f}); the 15 MOU countries: {m15.theta:+.2f} ({m15.lo:+.2f} to {m15.hi:+.2f}). "
           "In these groups GHES neither fell with the aid nor replaced it. The pooled co-movement comes from middle-income, "
           "low-dependence countries, where aid is small next to GHES and both move with the economy.",
           f"- Episode view: in {allr['ghes_below_trend']:.0%} of {allr['episodes']} aid-fall episodes GHES per person grew less "
           f"than usual (net of the year's common shock) and in {allr['ghes_above_trend']:.0%} it grew more; the median episode "
           f"shows {allr['median_adj']:+.2f} per US$1 of aid lost, the per-person dollar-weighted value {allr['dollar_weighted_adj']:+.2f} "
           f"and the population-weighted value {allr['pop_weighted_adj']:+.2f}.",
           f"- Subsample thetas run from {S.theta.min():+.2f} to {S.theta.max():+.2f}; {n_sig} of {len(S)} subsample CIs exclude zero "
           "(see Step 2). No group shows replacement.",
           f"- Leave-one-out: no single country moves theta by more than {J["shift"].abs().max():.3f}; it is not driven by one outlier.",
           "- Caveats: IHME estimates (GHES and DAH are modelled series with their own uncertainty); DAH here is all health aid, "
           "not the four programme areas the dashboard models; constant 2023 US$ per person; two-year window; episodes are "
           "statistical falls in disbursements (campaign timing, Gavi tranches) as well as policy cuts, which biases the "
           "response toward zero; the panel is 'what happened', not 'what governments could do'. The dashboard default "
           "(No Government Replacement) is consistent with this evidence; it is not evidence that replacement is impossible.", ""]
    (HERE / "RESULTS_fiscal_history.md").write_text("\n".join(md))
    print("wrote RESULTS_fiscal_history.md;", f"theta {full['theta']:+.3f}; episodes {len(E)}; median adj {allr['median_adj']:+.2f}")


if __name__ == "__main__":
    main()
