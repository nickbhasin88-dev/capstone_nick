"""
W-8 Concentration and W-9 thresholds (audit/concentration).
W-8: under the America First MOUs preset, which countries and services account for 80% of the coverage loss, and
     whether a short protected list (countries, or country x service lines) would preserve most of it and at what
     cost in modelled money. Two variants: the full preset as precomputed (MOU schedule plus the US multilateral
     exits; reconciles with model_data/all_countries_America_First_MOUs.csv) and the US bilateral MOU schedule only.
W-9: for each country, the constant cut to US direct-channel aid at which ART coverage (people on ART / people living
     with HIV, the model's definition) falls below 95% and 90%, TB treatment coverage below 90% (End TB) and DTP3
     below 90% (IA2030), and where the signed MOU schedule puts each country year by year.
Dashboard defaults (no government response, death-rate trends on), central runs (coverage is a money-to-people
calculation; the continuity assumption and caps are flagged), 16 MOU countries with schedule data (South Sudan is in
the precomputed file and is kept here for reconciliation; the reallocation audit's 15 exclude it).

    .venv/bin/python audit/concentration/run_concentration.py

Outputs: RESULTS_concentration.md, loss_by_line.csv, thresholds.csv. Read-only with respect to the model.
"""
from __future__ import annotations

import logging
import sys
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "audit" / "reallocation"))
logging.disable(logging.WARNING)
import health_model as hm  # noqa: E402
import scenarios as scn  # noqa: E402
import run_reallocation_2027 as rr  # noqa: E402

fmt, sfmt, md_table = rr.fmt, rr.sfmt, rr.md_table
LINE_NAME = {"hiv_art": "ART", "tb_ds": "TB treatment (DS)", "tb_dr": "TB treatment (DR)", "mal_itn": "Bednets", "mal_irs": "Spraying",
             "mal_cm": "Malaria treatment", "imm": "Vaccines", "hiv_pmtct": "PMTCT", "hiv_prev": "HIV prevention", "hiv_ovc": "OVC"}
TREAT = ["hiv_art", "tb_ds", "tb_dr", "imm"]
GRID = np.linspace(0, 1, 101)


def main():
    I, P = hm.load_inputs(), hm.load_params()
    ci = I["ci"]
    signed = set(scn.mou_signed()["iso3"])
    isos = [c for c in ci.index if c in signed and scn.mou_schedule(ci, c)[0] is not None]
    names = {i: str(ci.loc[i].get("country", i)) for i in isos}
    nm = pd.read_csv(ROOT / "model_data" / "mou_signed.csv").set_index("iso3")["country"].to_dict()
    names = {i: nm.get(i, i) for i in isos}
    F = hm.Fiscal(*scn.DEFAULT_FISCAL)
    pre = pd.read_csv(scn.precomputed_path(hm.MODEL_DIR, rr.PRESET)).set_index("iso3")

    def run(i, sc):
        return hm.run_country(i, sc, F, I, P, n_draws=0, keep_draws=True, mortality_trend=rr.TREND)

    md = ["# W-8 Concentration and W-9 thresholds under the America First MOUs preset (no model changes)", "",
          f"Generated by `audit/concentration/run_concentration.py`. {len(isos)} MOU countries with schedule data, dashboard defaults, "
          "central runs. People on service are yearly full-cost equivalents after the 15% continuity assumption; 'per year' is "
          "the 2026-2030 average (the MOU cuts deepen over time, so 2030 is above the average).", ""]
    # ------------------------------------------------------------------ W-8
    recs = {}
    for variant, bil in (("Full preset (MOU schedule + US multilateral exits)", False), ("US bilateral MOU schedule only", True)):
        rows = []
        for i in isos:
            sc = scn.build_scenario(rr.PRESET, {}, ci)
            if bil:
                sc.pair = {}
            r = run(i, sc)
            L = r["lines"]
            for l in hm.ALL_DIRECT:
                x = L[L.line == l].iloc[0]
                rows.append({"variant": variant, "iso3": i, "country": names[i], "line": l, "service": LINE_NAME[l], "units_per_year": float(x["units_lost"]),
                             "units_peak": float(x["units_lost_peak"]), "need": float(x["need"]), "cov0": float(x["cov0"]), "cov_drop_pp": float(x["cov_drop_pp"]),
                             "money_lost_per_year": float(x["gross_loss_usd"]), "deaths_5y": float(x["deaths_5y"]), "capped": bool(x["capped"]), "excess": bool(x["donor_exceeds_cost"])})
            recs[(variant, i)] = float(r["totals"]["deaths_5y"])
        D = pd.DataFrame(rows)
        D.to_csv(HERE / "loss_by_line.csv", index=False, mode="w" if not bil else "a", header=not bil)
        d16 = sum(recs[(variant, i)] for i in isos)
        md += [f"## W-8 ({variant})", ""]
        if not bil:
            md += [f"Reconciliation: deaths 2026-30 for the {len(isos)} countries {d16:,.0f} here against {pre.loc[isos, 'deaths_5y'].sum():,.0f} in "
                   f"`all_countries_America_First_MOUs.csv` (largest relative difference by country {max(abs(recs[(variant, i)] - pre.loc[i, 'deaths_5y']) / pre.loc[i, 'deaths_5y'] for i in isos):.1e}); "
                   f"excluding South Sudan {d16 - recs[(variant, 'SSD')]:,.0f} (the reallocation audit's 356,197 with exits on).", ""]
        else:
            md += [f"Deaths 2026-30, {len(isos)} countries: {d16:,.0f}; excluding South Sudan {d16 - recs[(variant, 'SSD')]:,.0f} (RESULTS_2027.md Baseline: 189,629).", ""]
        # by service
        S = D.groupby("service").agg(units=("units_per_year", "sum"), money=("money_lost_per_year", "sum"), deaths=("deaths_5y", "sum")).sort_values("units", ascending=False)
        tot_money = D.money_lost_per_year.sum()
        md += ["By service (per year, totals):", "",
               md_table(["Service", "People losing it per year", "Share of all people", "Money lost on the line US$M/yr", "Share of service money", "Deaths 2026-30 (secondary)"],
                        [[s, fmt(r.units), f"{r.units / S.units.sum():.0%}", fmt(r.money / 1e6, 1), f"{r.money / tot_money:.0%}", fmt(r.deaths)] for s, r in S.iterrows()]), ""]
        # concentration for ART, treatment lines, all people
        for label, mask in (("ART patient-years", D.line == "hiv_art"), ("Treatment and vaccines (ART, TB, DTP3-type routine vaccines)", D.line.isin(TREAT)),
                            ("Bednets", D.line == "mal_itn"), ("All people on any of the six services", D.line.isin(["hiv_art", "tb_ds", "tb_dr", "mal_itn", "mal_irs", "mal_cm", "imm"]))):
            X = D[mask].groupby("country").agg(units=("units_per_year", "sum"), money=("money_lost_per_year", "sum")).sort_values("units", ascending=False)
            X["cum"] = X.units.cumsum() / X.units.sum()
            k80 = int((X.cum < 0.8).sum() + 1)
            top = X.head(k80)
            md += [f"**{label}:** {k80} of {len(X)} countries account for 80% of the loss ({', '.join(top.index)}: {top.units.sum() / X.units.sum():.0%} of the people, "
                   f"US${top.money.sum() / 1e6:,.1f}M/yr of the US${X.money.sum() / 1e6:,.1f}M/yr lost on these lines, {top.money.sum() / X.money.sum():.0%} of the money).", "",
                   md_table(["Country", "People per year", "Share", "Cumulative", "Money lost on these lines US$M/yr", "People per US$1M"],
                            [[c, fmt(r.units), f"{r.units / X.units.sum():.0%}", f"{r.cum:.0%}", fmt(r.money / 1e6, 1), fmt(r.units / (r.money / 1e6)) if r.money > 1e4 else "n/a"] for c, r in X.iterrows()]), ""]
        # protected list by country x line, ranked by people per dollar (treatment lines) and the cost
        T = D[D.line.isin(TREAT)].copy()
        T = T[T.units_per_year > 0]
        T["ppd"] = T.units_per_year / T.money_lost_per_year
        T = T.sort_values("ppd", ascending=False)
        T["cum_units"] = T.units_per_year.cumsum() / T.units_per_year.sum()
        T["cum_money"] = T.money_lost_per_year.cumsum() / tot_money
        rows = []
        for k in (5, 10, 15, 20, 30):
            sub = T.head(k)
            rows.append([k, f"{sub.units_per_year.sum() / T.units_per_year.sum():.0%}", fmt(sub.money_lost_per_year.sum() / 1e6, 1), f"{sub.money_lost_per_year.sum() / tot_money:.0%}",
                         f"{sub.deaths_5y.sum() / D.deaths_5y.sum():.0%}", "; ".join(f"{r.country} {r.service}" for r in sub.tail(k - (0 if k == 5 else [5, 10, 15, 20, 30][[5, 10, 15, 20, 30].index(k) - 1])).itertuples())])
        md += ["Protected list, treatment and vaccine lines only (country x service, ranked by people kept per modelled dollar): share of the treatment "
               "and vaccine people preserved by protecting the top k lines, and what that costs in the money the cuts remove from those lines "
               f"(total service money lost US${tot_money / 1e6:,.1f}M/yr; all direct lines):", "",
               md_table(["Lines protected", "Treatment/vaccine people preserved", "Money needed US$M/yr", "Share of all lost service money", "Share of all deaths 2026-30 on these lines (secondary)", "Lines added"], rows), ""]
    # ------------------------------------------------------------------ W-9 thresholds
    md += ["## W-9 Thresholds: the cut at which coverage crosses a target", "",
           "A constant cut (the same fraction in every year 2026-2030) to US direct-channel aid only (no multilateral exits), scanned "
           "from 0% to 100% in 1% steps. Coverage after = baseline coverage - people losing the service / people in need (the "
           "model's definition; ART among all people living with HIV, TB treatment = WHO case detection, DTP3 among births). "
           "Thresholds: ART 95% and 90%, TB treatment 90% (End TB), DTP3 90% (IA2030). 'Floor' is coverage at a 100% cut: it is "
           "bounded by the donor-funded pool (external share of spending x people covered) and the 15% continuity assumption, so a "
           "country can be unable to reach a threshold at any cut. The last columns place the signed MOU schedule (US bilateral "
           "only): the deepest yearly cut and the first year each threshold is crossed.", ""]
    thr_rows, csv = [], []
    for i in isos:
        sc_s = scn.build_scenario(rr.PRESET, {}, ci)
        sc_s.pair = {}
        r_s = run(i, sc_s)
        L0 = r_s["lines"].set_index("line")
        cov = {}
        for f in GRID:
            sc = scn.build_scenario(rr.PRESET, {}, ci)
            sc.pair = {}
            sc.us_direct_path_by_country[i] = [float(f)] * 5
            r = run(i, sc)
            U = r["draws"]["units"]
            L = r["lines"].set_index("line")
            cov[f] = {"ART": L.loc["hiv_art", "cov0"] - U["hiv_art"][0, 0] / L.loc["hiv_art", "need"],
                      "TB": L.loc["tb_ds", "cov0"] - U["tb_ds"][0, 0] / L.loc["tb_ds", "need"],
                      "DTP3": L.loc["imm", "cov0"] - U["imm"][0, 0] / L.loc["imm", "need"]}
        C = pd.DataFrame(cov).T

        def cross(col, target):
            c0 = C[col].iloc[0]
            if np.isnan(c0) or c0 < target:
                return "below already" if not np.isnan(c0) else "n/a"
            below = C[C[col] < target]
            if not len(below):
                return f"never (floor {C[col].iloc[-1]:.0%})"
            f1 = below.index[0]
            f0 = C.index[C.index.get_loc(f1) - 1]
            fx = f0 + (C.loc[f0, col] - target) / (C.loc[f0, col] - C.loc[f1, col]) * (f1 - f0)
            return f"{fx:.0%}"

        cuts = sc_s.us_direct_path_by_country[i]
        U = r_s["draws"]["units"]
        art_by_year = [L0.loc["hiv_art", "cov0"] - U["hiv_art"][0, t] / L0.loc["hiv_art", "need"] for t in range(5)]
        tb_by_year = [L0.loc["tb_ds", "cov0"] - U["tb_ds"][0, t] / L0.loc["tb_ds", "need"] for t in range(5)]

        def first_year(series, target):
            for t, v in enumerate(series):
                if v < target <= series[0] + 1e-9:
                    return str(2026 + t)
            return "no" if series[0] >= target else "below already"

        thr_rows.append([names[i], f"{C['ART'].iloc[0]:.0%}", cross("ART", 0.95), cross("ART", 0.90), f"{C['ART'].iloc[-1]:.0%}", f"{C['TB'].iloc[0]:.0%}", cross("TB", 0.90),
                         f"{C['DTP3'].iloc[0]:.0%}", cross("DTP3", 0.90), f"{max(cuts):.0%} ({2026 + int(np.argmax(cuts))})",
                         " / ".join(f"{v:.0%}" for v in art_by_year), first_year(art_by_year, 0.95), first_year(art_by_year, 0.90), first_year(tb_by_year, 0.90)])
        csv.append({"iso3": i, "country": names[i], "art_cov0": C["ART"].iloc[0], "art_floor": C["ART"].iloc[-1], "cut_art95": cross("ART", 0.95), "cut_art90": cross("ART", 0.90),
                    "tb_cov0": C["TB"].iloc[0], "cut_tb90": cross("TB", 0.90), "dtp3_cov0": C["DTP3"].iloc[0], "cut_dtp90": cross("DTP3", 0.90), "mou_max_cut": max(cuts),
                    **{f"art_cov_{2026 + t}": art_by_year[t] for t in range(5)}, "donor_share_hiv": float(L0.loc["hiv_art", "donor_share_ext"]),
                    "donor_funded_art": float(L0.loc["hiv_art", "donor_funded_units"])})
    pd.DataFrame(csv).to_csv(HERE / "thresholds.csv", index=False)
    md += [md_table(["Country", "ART coverage now", "Cut for ART < 95%", "Cut for ART < 90%", "ART floor at 100% cut", "TB treatment now", "Cut for TB < 90%", "DTP3 now", "Cut for DTP3 < 90%",
                     "Signed MOU: deepest cut (year)", "ART coverage 2026-30 under the signed MOU", "ART < 95% from", "ART < 90% from", "TB < 90% from"], thr_rows), ""]
    md += ["Caveats: baseline ART coverage is the UNAIDS/World Bank share of all people living with HIV on treatment (Botswana is "
           "recorded as 100%); the 95-95-95 targets are defined on diagnosed people and are not the same quantity. The model holds "
           "people in need constant and treats coverage as money / unit cost, so a crossing is a linear projection with no "
           "re-prioritisation by the programme. TB treatment coverage uses WHO case detection, capped at 100%.", ""]
    (HERE / "RESULTS_concentration.md").write_text("\n".join(md))
    print("wrote RESULTS_concentration.md, loss_by_line.csv, thresholds.csv")


if __name__ == "__main__":
    main()
